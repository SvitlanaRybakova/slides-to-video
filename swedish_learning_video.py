import re

ASS_FILE = "/content/subtitles.ass"

def ass_time(seconds):
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    secs = seconds % 60

    return (
        f"{hours}:"
        f"{minutes:02d}:"
        f"{secs:05.2f}"
    )

def make_groups(words, max_words=7):
    groups = []
    current = []

    for word in words:
        current.append(word)

        # End a group at punctuation or after max_words
        if (
            re.search(r'[.!?]', word["word"])
            or len(current) >= max_words
        ):
            groups.append(current)
            current = []

    if current:
        groups.append(current)

    return groups


def generate_ass(words, output_file):

    header = """[Script Info]
ScriptType: v4.00+
PlayResX: 1920
PlayResY: 1080
WrapStyle: 2
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,DejaVu Sans,66,&H00FFFFFF,&H0000FFFF,&H80000000,&H80000000,-1,0,0,0,100,100,1,0,1,3,1,2,120,120,180,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

    events = []

    groups = make_groups(words)

    for group in groups:

        for i, active_word in enumerate(group):

            start = active_word["start"]

            if i + 1 < len(group):
                end = group[i + 1]["start"]
            else:
                end = active_word["end"]

            end = max(end, start + 0.08)

            tokens = []

            for word in group:

                clean_word = word["word"].strip()

                # Escape ASS special characters
                clean_word = (
                    clean_word
                    .replace("\\", "\\\\")
                    .replace("{", "\\{")
                    .replace("}", "\\}")
                )

                if word is active_word:
                    tokens.append(
                        r"{\c&H0000FFFF&}" + clean_word +
                        r"{\c&H00FFFFFF&}"
                    )
                else:
                    tokens.append(clean_word)

            subtitle = " ".join(tokens)

            events.append(
                f"Dialogue: 0,"
                f"{ass_time(start)},"
                f"{ass_time(end)},"
                f"Default,,0,0,0,,{subtitle}"
            )

    with open(output_file, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(events))

    print("ASS subtitles generated:", output_file)


